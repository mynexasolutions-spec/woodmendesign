/** Short wood label for cards, e.g. 'Mango Wood' (avoids 'Wood Wood' for values like 'Wood & Metal'). */
export const woodLabel = (woodType: string): string => {
  const first = woodType.split(' ')[0];
  return /^wood$/i.test(first) ? 'Wood' : `${first} Wood`;
};

